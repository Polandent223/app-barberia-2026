import test from "node:test";
import assert from "node:assert/strict";
import {randomUUID} from "node:crypto";
import {createRequire} from "node:module";
import {initializeApp as initClient,deleteApp as deleteClient} from "firebase/app";
import {getAuth,connectAuthEmulator,createUserWithEmailAndPassword,signOut} from "firebase/auth";
import {getFunctions,connectFunctionsEmulator,httpsCallable} from "firebase/functions";
const projectId="demo-sambrix-qa";
const local=/^(localhost|127\.0\.0\.1):\d+$/;
if(!local.test(process.env.FIRESTORE_EMULATOR_HOST||"")||!local.test(process.env.FIREBASE_AUTH_EMULATOR_HOST||"")||process.env.GCLOUD_PROJECT!==projectId)throw Error("QA requires local emulators and demo project.");
const require=createRequire(new URL("../functions/package.json",import.meta.url));
const {initializeApp,deleteApp}=require("firebase-admin/app");
const {getFirestore}=require("firebase-admin/firestore");
const admin=initializeApp({projectId},"sambrix-qa-admin"),db=getFirestore(admin);
const clients=[];
async function client(name,register=true){
 const app=initClient({projectId,apiKey:"demo-api-key",authDomain:projectId+".firebaseapp.com",appId:"1:123:web:qa"},name+"-"+randomUUID());
 clients.push(app);
 const auth=getAuth(app);connectAuthEmulator(auth,"http://"+process.env.FIREBASE_AUTH_EMULATOR_HOST,{disableWarnings:true});
 const f=getFunctions(app,"us-central1");connectFunctionsEmulator(f,"127.0.0.1",5001);
 const user=register?(await createUserWithEmailAndPassword(auth,name+"-"+randomUUID()+"@example.test","QA-password-12345")).user:null;
 return {auth,uid:user?.uid,sell:async data=>(await httpsCallable(f,"sambrixSellProducts")(data)).data,refund:async data=>(await httpsCallable(f,"sambrixReturnProducts")(data)).data};
}
test("callable POS uses actual emulator Auth tokens and commits exactly once",{timeout:90000},async()=>{
 const owner=await client("owner"),cashier=await client("cashier"),other=await client("other"),anon=await client("anon",false);
 const id="qa-callable-"+randomUUID(),company=db.doc("businesses/"+id),st=name=>company.collection("state").doc(name);
 const batch=db.batch();
 batch.set(db.doc("platform/config"),{ownerUid:"qa-root",shopServerEnabled:false});
 batch.set(company,{id,status:"Activo",planId:"plan-pro",nextPayment:"2099-12-31",accessSuspended:false});
 for(const [user,role] of [[owner,"owner"],[cashier,"cashier"],[other,"owner"]]){
  const businessId=user===other?"qa-other":id;
  batch.set(db.doc("platform_users/"+user.uid),{uid:user.uid,role:"business_user",active:true,businessId});
  if(user!==other)batch.set(company.collection("members").doc(user.uid),{uid:user.uid,businessId:id,role,active:true});
 }
 batch.set(st("config"),{businessId:id,syncRevision:1,payload:{business:{currency:"$",timezone:"America/Caracas"},meta:{branchId:"main"}}});
 batch.set(st("inventory"),{businessId:id,syncRevision:1,payload:{products:[{id:"p1",name:"Producto 1",price:4.25,stock:5,businessId:id},{id:"p2",name:"Producto 2",price:3,stock:4,businessId:id}],stockMoves:[],shopOrders:[]}});
 batch.set(st("finance"),{businessId:id,syncRevision:1,payload:{cash:[],sales:[]}});
 await batch.commit();
 const request={businessId:id,requestId:randomUUID(),method:"Efectivo",items:[{id:"p1",qty:2,price:4.25},{id:"p2",qty:1,price:3}]};
 await assert.rejects(anon.sell(request),e=>e.code==="functions/unauthenticated");
 await assert.rejects(owner.sell(request),e=>e.code==="functions/failed-precondition");
 await db.doc("platform/config").update({shopServerEnabled:true});
 await assert.rejects(other.sell({...request,actor:owner.uid}),e=>e.code==="functions/permission-denied");
 await assert.rejects(cashier.sell({...request,items:[{id:"p1",qty:1,price:1}]}),e=>e.code==="functions/failed-precondition");
 const result=await cashier.sell(request);
 assert.equal(result.sale.total,11.5);assert.equal(result.sale.createdBy,cashier.uid);
 assert.deepEqual(await cashier.sell(request),result);
 await assert.rejects(cashier.sell({...request,items:[{id:"p1",qty:1,price:4.25}]}));
 let f=(await st("finance").get()).data().payload,i=(await st("inventory").get()).data().payload;
 assert.equal(f.sales.length,1);assert.equal(f.cash.length,1);assert.equal(f.cash[0].amount,11.5);assert.deepEqual(i.products.map(p=>p.stock),[3,3]);
 const refund={businessId:id,requestId:randomUUID(),originalOperationId:result.sale.shopOperationId,reason:"Mercancía recibida y dinero devuelto"};
 await assert.rejects(cashier.refund(refund),e=>e.code==="functions/permission-denied");
 const returned=await owner.refund(refund);assert.equal(returned.amount,11.5);assert.deepEqual(await owner.refund(refund),returned);
 f=(await st("finance").get()).data().payload;i=(await st("inventory").get()).data().payload;
 assert.equal(f.sales.length,1);assert.equal(f.cash.length,2);assert.equal(f.cash[1].type,"Egreso");assert.deepEqual(i.products.map(p=>p.stock),[5,4]);
 await company.update({accessSuspended:true});
 await assert.rejects(cashier.sell({...request,requestId:randomUUID()}),e=>e.code==="functions/permission-denied");
 await company.update({accessSuspended:false});
 await signOut(cashier.auth);
 await assert.rejects(cashier.sell({...request,requestId:randomUUID()}),e=>e.code==="functions/unauthenticated");
 console.log("POS CALLABLE QA: Auth real del emulador, roles, bloqueo, idempotencia, venta y devolución aprobados.");
});
test.after(async()=>{await Promise.all(clients.map(app=>deleteClient(app)));await db.terminate();await deleteApp(admin);});
